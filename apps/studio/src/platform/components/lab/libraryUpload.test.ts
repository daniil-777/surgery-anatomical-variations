import { describe, expect, it } from "vitest";
import type { LabLibraryExport } from "../../bridge/labSession";
import { MemoryBackend } from "../../core/memory";
import { PlatformError } from "../../core/types";
import { friendlyError, isCancellation } from "./friendlyError";
import {
  LIBRARY_METADATA_BUDGET,
  exportToRequest,
  libraryFilename,
  libraryItemMetadata,
  libraryTags,
  libraryTitle,
  uniqueFilenames,
  uploadToLibrary,
} from "./libraryUpload";

const CLAIMS = {
  evidence: "Generated by the browser shape model from the committed spec.",
  limitations: ["Vertex colours are a bake of the procedural material, not a texture set."],
};

async function signedIn(): Promise<MemoryBackend> {
  const backend = new MemoryBackend();
  await backend.auth.signUp({ email: "lab@example.test", password: "correct horse battery" });
  return backend;
}

describe("library names", () => {
  it("keeps titles within 1–120 characters", () => {
    expect(libraryTitle("  Liver   v2 ")).toBe("Liver v2");
    expect(libraryTitle("   ", "Snapshot")).toBe("Snapshot");
    const long = libraryTitle("x".repeat(300));
    expect(long.length).toBe(120);
    expect(long.endsWith("…")).toBe(true);
  });

  it("makes file names safe and unique", () => {
    expect(libraryFilename("a/b\\c.glb")).toBe("a-b-c.glb");
    expect(libraryFilename("..hidden.json")).toBe("hidden.json");
    expect(libraryFilename("")).toBe("file");
    expect(libraryFilename(`${"n".repeat(200)}.webm`)).toMatch(/^n{175}\.webm$/);
    const files = uniqueFilenames([
      { filename: "Shape.glb", role: "mesh", blob: new Blob(["a"]) },
      { filename: "shape.glb", role: "mesh", blob: new Blob(["b"]) },
      { filename: "spec", role: "spec", blob: new Blob(["c"]) },
      { filename: "spec", role: "spec", blob: new Blob(["d"]) },
    ]);
    expect(files.map((file) => file.filename)).toEqual(["Shape.glb", "shape 2.glb", "spec", "spec 2"]);
  });

  it("tidies tags the way the database checks them", () => {
    expect(libraryTags([" liver ", "Liver", "", "x".repeat(40), "a\u0007b"])).toEqual(["liver", "x".repeat(32), "a b"]);
    expect(libraryTags(Array.from({ length: 30 }, (_, index) => `t${index}`))).toHaveLength(20);
  });
});

describe("library metadata", () => {
  it("copies claims verbatim and records provenance", () => {
    const metadata = libraryItemMetadata({
      claims: { ...CLAIMS, rights: "CC BY 4.0" },
      provenance: { via: "lab-export", labId: "organ", labTitle: "Organ Design", projectId: "p", versionId: "v", unsavedChanges: false, exportId: "shape" },
      labVersions: { generator: "atlas-2" },
      lab: { organ: "liver" },
    });
    expect(metadata.claims).toEqual({ ...CLAIMS, rights: "CC BY 4.0" });
    expect(metadata.provenance).toMatchObject({ via: "lab-export", labId: "organ", projectId: "p", versionId: "v", exportId: "shape" });
    expect(metadata.labVersions).toEqual({ generator: "atlas-2" });
    expect(metadata.lab).toEqual({ organ: "liver" });
  });

  it("leaves lab metadata out when it does not fit the 64 KB column", () => {
    const metadata = libraryItemMetadata({
      claims: CLAIMS,
      provenance: { via: "snapshot", labId: null, labTitle: null, projectId: null, versionId: null, unsavedChanges: true },
      lab: { blob: "x".repeat(LIBRARY_METADATA_BUDGET) },
    });
    expect(metadata.lab).toBeUndefined();
    expect(metadata.labMetadataOmitted).toBe(true);
  });
});

describe("uploadToLibrary", () => {
  it("uploads every file and the thumbnail, then creates the item with its provenance", async () => {
    const backend = await signedIn();
    const exported: LabLibraryExport = {
      kind: "shape",
      title: "Liver variation",
      description: "From the organ lab",
      tags: ["liver"],
      files: [
        { filename: "liver.glb", role: "mesh", blob: new Blob([new Uint8Array([1, 2, 3])], { type: "model/gltf-binary" }) },
        { filename: "spec.json", role: "spec", blob: new Blob(['{"organ":"liver"}'], { type: "application/json" }) },
      ],
      thumbnail: new Blob([new Uint8Array([9, 9, 9, 9])], { type: "image/png" }),
      metadata: { organ: "liver" },
      claims: CLAIMS,
    };
    const request = exportToRequest(exported, { exportId: "shape", labId: "organ", labTitle: "Organ Design", projectId: null, versionId: null, unsavedChanges: false });
    const progress: number[] = [];
    const item = await uploadToLibrary(backend, request, { onProgress: ({ loaded, total }) => progress.push(loaded / total) });
    expect(item.kind).toBe("shape");
    expect(item.title).toBe("Liver variation");
    expect(item.tags).toEqual(["liver"]);
    expect(item.thumbnailAssetId).not.toBeNull();
    expect(item.metadata.claims).toEqual(CLAIMS);
    const stored = await backend.library.get(item.id);
    expect(stored.files?.map((file) => [file.filename, file.role, file.position])).toEqual([
      ["liver.glb", "mesh", 0],
      ["spec.json", "spec", 1],
    ]);
    expect(progress.at(-1)).toBe(1);
    const bytes = new Uint8Array(await (await backend.assets.get(stored.files?.[0]?.assetId ?? "")).arrayBuffer());
    expect([...bytes]).toEqual([1, 2, 3]);
  });

  it("refuses an item without files before uploading anything", async () => {
    const backend = await signedIn();
    await expect(
      uploadToLibrary(backend, { kind: "image", title: "x", labId: null, sourceProjectId: null, sourceVersionId: null, files: [], thumbnail: null, metadata: {} }),
    ).rejects.toThrow(/no files/);
  });

  it("surfaces the backend's refusal as a friendly sentence", async () => {
    const backend = new MemoryBackend();
    let caught: unknown = null;
    try {
      await uploadToLibrary(backend, {
        kind: "image",
        title: "x",
        labId: null,
        sourceProjectId: null,
        sourceVersionId: null,
        files: [{ filename: "a.png", role: "primary", blob: new Blob([new Uint8Array([1])], { type: "image/png" }) }],
        thumbnail: null,
        metadata: {},
      });
    } catch (error) {
      caught = error;
    }
    expect(caught).toBeInstanceOf(PlatformError);
    expect(friendlyError(caught)).toBe("Your session has ended. Sign in again to keep saving.");
  });
});

describe("friendlyError", () => {
  it("maps platform, session and host errors by name, not by realm", () => {
    expect(friendlyError(new PlatformError("quota_exceeded"))).toMatch(/storage is full/);
    expect(friendlyError({ name: "PlatformError", code: "network", message: "x" })).toMatch(/can't be reached/);
    expect(friendlyError({ name: "PlatformError", code: "invalid_input", message: "A named version needs a name." })).toBe("A named version needs a name.");
    expect(friendlyError({ name: "PlatformError", code: "limit_reached", detail: "at most 100 projects on this plan" })).toMatch(/number of projects/);
    expect(friendlyError({ name: "SessionError", code: "lab_busy", message: "…" })).toMatch(/lab is busy/);
    expect(friendlyError({ name: "LabRightsError", message: "“X” is research-only (research use only): it cannot be added to the Library." })).toBe(
      "“X” is research-only (research use only): it cannot be added to the Library.",
    );
    expect(friendlyError({ name: "LabBusyError", reason: "recording" })).toBe("The lab is busy (recording). Try again when it has finished.");
    expect(friendlyError(new Error("boom"), "The version couldn't be restored.")).toBe("The version couldn't be restored.");
    expect(friendlyError(null)).toBe("Something went wrong.");
  });

  it("recognises cancellations", () => {
    expect(isCancellation({ name: "AbortError" })).toBe(true);
    expect(isCancellation(new PlatformError("aborted"))).toBe(true);
    expect(isCancellation(new PlatformError("network"))).toBe(false);
  });
});
